export function normalizePhrase(phrase: string): string {
  return phrase.normalize("NFKC").toLowerCase().trim()
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/\s+/g, " ")
    .replace(/[.!?]+$/g, "").trim();
}

export function compactPhrase(phrase: string): string {
  return normalizePhrase(phrase).replace(/[\s\-\u2010-\u2015]/g, "");
}

export function matchTermVariants(phrase: string, entries: CorpusTerm[]): CorpusTerm | null {
  const input = normalizePhrase(phrase);
  const exact = entries.filter(entry => [entry.term, ...(entry.aliases ?? [])].some(alias => normalizePhrase(alias) === input));
  if (exact.length === 1) return exact[0];
  if (exact.length > 1) return null;
  const compact = compactPhrase(input);
  const variants = entries.filter(entry => [entry.term, ...(entry.aliases ?? [])].some(alias => compactPhrase(alias) === compact));
  return variants.length === 1 ? variants[0] : null;
}

function editDistance(a: string, b: string): number {
  const row = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let diagonal = row[0];
    row[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const previous = row[j];
      row[j] = Math.min(row[j] + 1, row[j - 1] + 1, diagonal + (a[i - 1] === b[j - 1] ? 0 : 1));
      diagonal = previous;
    }
  }
  return row[b.length];
}

export function matchCorpus(phrase: string): CorpusTerm | null {
  return matchTermVariants(phrase, CORPUS);
}

// Suggestions never grant a verified meaning. The visitor must explicitly
// choose a suggestion before it becomes a corpus match.
export function suggestCorpus(phrase: string): CorpusTerm | null {
  const input = normalizePhrase(phrase);
  if (matchCorpus(input)) return null;
  // Short words need exact matches. Longer phrases permit only a clear typo,
  // with the same word count and a unique best candidate.
  if (input.length < 7) return null;
  const threshold = input.length >= 16 ? 2 : 1;
  const candidates = CORPUS.map((entry) => ({
    entry,
    distance: input.split(" ").length === normalizePhrase(entry.term).split(" ").length
      ? editDistance(input, normalizePhrase(entry.term)) : Infinity,
  })).filter(({ distance }) => distance <= threshold).sort((a, b) => a.distance - b.distance);
  if (!candidates.length || candidates[0].distance === candidates[1]?.distance) return null;
  return candidates[0].entry;
}

export function validatePhrase(value: unknown): { phrase: string } | { error: string } {
  if (typeof value !== "string") return { error: "Type a Singlish phrase first." };
  if (/[\u0000-\u001f\u007f]/.test(value)) return { error: "Use a short phrase without control characters." };
  const phrase = normalizePhrase(value);
  if (phrase.length < 2 || phrase.length > 120) return { error: "Keep your phrase between 2 and 120 characters." };
  if (!/[\p{L}]/u.test(phrase)) return { error: "Your phrase needs a few words or letters." };
  if (isBlockedPhrase(phrase)) return { error: "Keep this shared wall friendly. Try another phrase." };
  return { phrase };
}

export function isBlockedPhrase(phrase: string): boolean {
  // Practical event-wall guard; intentionally does not treat everyday Singlish
  // expressions such as “die die must” or friendly teasing as abuse.
  return /\b(?:fuck(?:ing|er|ed|s)?|motherfucker|cunt|nigg(?:er|a)s?|faggot|rape|raping|kill yourself)\b/i.test(phrase)
    || /(?:https?:\/\/|www\.|[\w.+-]+@[\w.-]+\.[a-z]{2,})/i.test(phrase);
}
